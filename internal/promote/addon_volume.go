package promote

import (
	"fmt"
	"strings"
)

// volumeEngine renders a volume for the applications of a project.
//
// Some databases are files: a SQLite database is a file on a disk. There
// is nothing to run, and nothing to reach: the application finds a disk
// mounted where it expects it.
//
// The engine writes the claim, and declares the volume the applications
// mount. The claim is named after the project and the addon, so two
// applications of the same project do not share their disk.
type volumeEngine struct{}

func (volumeEngine) Name() string { return "volume" }

func (volumeEngine) Render(dir string, spec AddonSpec, platform Platform) (AddonResult, error) {
	p := platform.withDefaults()
	namespace := strings.TrimSpace(spec.Namespace)
	if namespace == "" {
		namespace = p.ReleaseNamespace
	}
	name := sanitizeName(spec.Project) + "-" + sanitizeName(spec.Name)
	entry, ok := AddonCatalogEntryForEngine("volume")
	if !ok {
		return AddonResult{}, fmt.Errorf("the type sqlite is not in the catalogue")
	}
	plan, err := entry.Plan(spec.Plan, spec.Params)
	if err != nil {
		return AddonResult{}, err
	}
	path := strings.TrimSpace(spec.Path)
	if path == "" {
		path = strings.TrimSpace(entry.Path)
	}
	if path == "" {
		return AddonResult{}, fmt.Errorf("the addon %q has no path: the manifest says where the volume is mounted", spec.Name)
	}
	if !strings.HasPrefix(path, "/") {
		return AddonResult{}, fmt.Errorf("the path %q of the addon %q is not an absolute path", path, spec.Name)
	}
	claim := name
	mount := AddonMount{
		Name:  sanitizeName(spec.Name),
		Path:  path,
		Claim: claim,
		Size:  plan.Storage,
	}
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack from the project manifest.\n")
	b.WriteString("# The disk of the applications that use this addon.\n")
	b.WriteString("apiVersion: v1\n")
	b.WriteString("kind: PersistentVolumeClaim\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + claim + "\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("  labels:\n")
	b.WriteString("    kuberpack.io/addon: " + entry.Kind + "\n")
	b.WriteString("    kuberpack.io/addon-name: " + sanitizeName(spec.Name) + "\n")
	b.WriteString("    kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  accessModes: [\"ReadWriteOnce\"]\n")
	b.WriteString("  resources:\n")
	b.WriteString("    requests:\n")
	b.WriteString("      storage: " + plan.Storage + "\n")
	if err := writeAddonFiles(dir, addonFile{name: "volume.yaml", content: b.String()}); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{
		name:    "kustomization.yaml",
		content: addonKustomization("volume.yaml"),
	}); err != nil {
		return AddonResult{}, err
	}
	// A volume has no pods, no port and no network: it is a disk. It
	// gives the applications a volume, nothing else.
	return AddonResult{
		Mounts: []AddonMount{mount},
	}, nil
}
