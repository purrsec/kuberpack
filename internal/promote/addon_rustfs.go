package promote

import (
	"fmt"
	"strconv"
	"strings"
)

// rustfsEngine renders an S3-compatible object storage.
//
// The storage holds the backups of the databases: without it, a backup is a
// snapshot of the disk of a node, and it dies with the node.
//
// The credentials are born in the cluster, by a Job: they never pass
// through Kuberpack, and they are never in the repository.
type rustfsEngine struct{}

func (rustfsEngine) Name() string { return "rustfs" }

func (rustfsEngine) Render(dir string, spec AddonSpec, platform Platform) (AddonResult, error) {
	p := platform.withDefaults()
	entry, ok := AddonCatalogEntry("rustfs")
	if !ok {
		return AddonResult{}, fmt.Errorf("the type rustfs is not in the catalogue")
	}
	plan, err := entry.Plan(spec.Plan, spec.Params)
	if err != nil {
		return AddonResult{}, err
	}
	namespace := strings.TrimSpace(spec.Namespace)
	if namespace == "" {
		namespace = p.ReleaseNamespace
	}
	name := sanitizeName(spec.Project) + "-" + sanitizeName(spec.Name)
	aname := sanitizeName(spec.Name)
	secret := strings.ReplaceAll(entry.Bootstrap.Secret, "{{name}}", name)
	if secret == "" {
		secret = name + "-app"
	}

	imageRef := strings.TrimSpace(p.AddonImages["rustfs"])
	if imageRef == "" {
		imageRef = entry.Image
	}
	image, err := p.PinnedImage(imageRef)
	if err != nil {
		return AddonResult{}, err
	}
	bootstrapImage, err := p.PinnedImage(entry.Bootstrap.Image)
	if err != nil {
		return AddonResult{}, err
	}

	var stateful strings.Builder
	stateful.WriteString("# Generated by Kuberpack from the project manifest.\n")
	stateful.WriteString("apiVersion: apps/v1\n")
	stateful.WriteString("kind: StatefulSet\n")
	stateful.WriteString("metadata:\n")
	stateful.WriteString("  name: " + name + "\n")
	stateful.WriteString("  namespace: " + namespace + "\n")
	stateful.WriteString("  labels:\n")
	stateful.WriteString("    kuberpack.io/addon: " + entry.Kind + "\n")
	stateful.WriteString("    kuberpack.io/addon-name: " + aname + "\n")
	stateful.WriteString("    kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	stateful.WriteString("spec:\n")
	stateful.WriteString("  serviceName: " + name + "\n")
	stateful.WriteString("  replicas: " + strconv.Itoa(plan.Instances) + "\n")
	stateful.WriteString("  selector:\n")
	stateful.WriteString("    matchLabels:\n")
	stateful.WriteString("      app.kubernetes.io/name: " + name + "\n")
	stateful.WriteString("      app.kubernetes.io/part-of: kuberpack\n")
	stateful.WriteString("  template:\n")
	stateful.WriteString("    metadata:\n")
	stateful.WriteString("      labels:\n")
	stateful.WriteString("        app.kubernetes.io/name: " + name + "\n")
	stateful.WriteString("        app.kubernetes.io/part-of: kuberpack\n")
	stateful.WriteString("        kuberpack.io/addon: " + entry.Kind + "\n")
	stateful.WriteString("        kuberpack.io/addon-name: " + aname + "\n")
	stateful.WriteString("        kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	stateful.WriteString("    spec:\n")
	stateful.WriteString("      containers:\n")
	stateful.WriteString("        - name: rustfs\n")
	stateful.WriteString("          image: " + image + "\n")
	stateful.WriteString("          imagePullPolicy: IfNotPresent\n")
	stateful.WriteString("          args: [\"/data\"]\n")
	stateful.WriteString("          env:\n")
	stateful.WriteString("            - name: RUSTFS_ACCESS_KEY\n")
	stateful.WriteString("              valueFrom:\n")
	stateful.WriteString("                secretKeyRef:\n")
	stateful.WriteString("                  name: " + secret + "\n")
	stateful.WriteString("                  key: accessKeyId\n")
	stateful.WriteString("            - name: RUSTFS_SECRET_KEY\n")
	stateful.WriteString("              valueFrom:\n")
	stateful.WriteString("                secretKeyRef:\n")
	stateful.WriteString("                  name: " + secret + "\n")
	stateful.WriteString("                  key: secretAccessKey\n")
	stateful.WriteString("          ports:\n")
	stateful.WriteString("            - name: s3\n")
	stateful.WriteString("              containerPort: " + strconv.Itoa(entry.Port) + "\n")
	stateful.WriteString("          resources:\n")
	stateful.WriteString("            requests: { cpu: " + plan.Resources.Requests.CPU + ", memory: " + plan.Resources.Requests.Memory + " }\n")
	stateful.WriteString("            limits: { cpu: \"" + plan.Resources.Limits.CPU + "\", memory: \"" + plan.Resources.Limits.Memory + "\" }\n")
	stateful.WriteString("          volumeMounts:\n")
	stateful.WriteString("            - name: data\n")
	stateful.WriteString("              mountPath: /data\n")
	stateful.WriteString("  volumeClaimTemplates:\n")
	stateful.WriteString("    - metadata:\n")
	stateful.WriteString("        name: data\n")
	stateful.WriteString("      spec:\n")
	stateful.WriteString("        accessModes: [\"ReadWriteOnce\"]\n")
	stateful.WriteString("        resources:\n")
	stateful.WriteString("          requests:\n")
	stateful.WriteString("            storage: " + plan.Storage + "\n")
	if p.AddonStorageClass != "" {
		stateful.WriteString("        storageClassName: " + p.AddonStorageClass + "\n")
	}

	var service strings.Builder
	service.WriteString("# Generated by Kuberpack from the project manifest.\n")
	service.WriteString("apiVersion: v1\n")
	service.WriteString("kind: Service\n")
	service.WriteString("metadata:\n")
	service.WriteString("  name: " + name + "\n")
	service.WriteString("  namespace: " + namespace + "\n")
	service.WriteString("  labels:\n")
	service.WriteString("    kuberpack.io/addon: " + entry.Kind + "\n")
	service.WriteString("    kuberpack.io/addon-name: " + aname + "\n")
	service.WriteString("    kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	service.WriteString("spec:\n")
	service.WriteString("  selector:\n")
	service.WriteString("    app.kubernetes.io/name: " + name + "\n")
	service.WriteString("    app.kubernetes.io/part-of: kuberpack\n")
	service.WriteString("  ports:\n")
	service.WriteString("    - name: s3\n")
	service.WriteString("      port: " + strconv.Itoa(entry.Port) + "\n")
	service.WriteString("      targetPort: s3\n")

	job, rbac := addonBootstrap(name, namespace, bootstrapImage, secret, entry.Bootstrap.Keys)

	if err := writeAddonFiles(dir,
		addonFile{name: "rustfs.yaml", content: stateful.String()},
		addonFile{name: "service.yaml", content: service.String()},
		addonFile{name: "bootstrap-job.yaml", content: job},
		addonFile{name: "rbac.yaml", content: rbac},
		addonFile{name: "networkpolicy.yaml", content: addonNetworkPolicy(name, namespace, entry.Kind, aname,
			sanitizeName(spec.Project), []int{entry.Port}, "", spec)},
	); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{
		name:    "kustomization.yaml",
		content: addonKustomization("rustfs.yaml", "service.yaml", "bootstrap-job.yaml", "rbac.yaml", "networkpolicy.yaml"),
	}); err != nil {
		return AddonResult{}, err
	}

	// The endpoint is a literal: it says where the storage is, not how to
	// enter it.
	envs := []AddonEnv{{
		Name:  "S3_ENDPOINT",
		Value: "http://" + name + "." + namespace + ".svc.cluster.local:" + strconv.Itoa(entry.Port),
	}}
	for _, variable := range sortedKeys(entry.Env) {
		envs = append(envs, AddonEnv{
			Name:       variable,
			SecretName: secret,
			SecretKey:  entry.Env[variable],
		})
	}
	return AddonResult{
		Kind:    entry.Kind,
		Port:    entry.Port,
		Env:     envs,
		Secret:  secret,
		Service: name + "." + namespace + ".svc.cluster.local",
	}, nil
}
