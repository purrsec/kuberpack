package promote

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// PreviewDatabaseName is the CloudNativePG Cluster dedicated to a preview
// release (app-<app>-pr-<n>-db). It is empty by design: the app creates the
// schema with its own migrations, and production data never reaches it.
func PreviewDatabaseName(releaseName string) string {
	return sanitizeName(releaseName) + "-db"
}

func (p Platform) PreviewDatabasePath(releaseName string) string {
	return filepath.ToSlash(filepath.Join(p.withDefaults().AppDir(releaseName), "database.yaml"))
}

// ensurePreviewDatabase writes an empty CloudNativePG Cluster for the preview
// and makes sure the app kustomization lists it. No-op unless enabled.
//
// The preview database is the postgres engine, with its own image and its own
// storage: there is one implementation of a PostgreSQL database, not two.
func ensurePreviewDatabase(work string, spec AppSpec, p Platform) (bool, error) {
	p = p.withDefaults()
	if !spec.Preview || !spec.PreviewDatabase {
		return false, nil
	}
	engine, ok := AddonEngineFor("cnpg")
	if !ok {
		return false, fmt.Errorf("the engine cnpg is not available")
	}
	appDir := filepath.Join(work, filepath.FromSlash(p.AppDir(spec.Name)))
	dir := filepath.Join(appDir, "db")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return false, err
	}
	before, _ := os.ReadFile(filepath.Join(dir, "database.yaml"))
	preview := p
	preview.PostgresImage = p.PreviewDatabaseImage
	preview.PostgresStorage = p.PreviewDatabaseStorage
	preview.PostgresStorageClass = p.PreviewDatabaseClass
	if _, err := engine.Render(dir, AddonSpec{
		Project:   sanitizeName(spec.Name),
		Name:      "db",
		Namespace: p.ReleaseNamespace,
	}, preview); err != nil {
		return false, err
	}
	after, err := os.ReadFile(filepath.Join(dir, "database.yaml"))
	if err != nil {
		return false, err
	}
	changed := string(before) != string(after)

	// The database of a preview is isolated: only the app of the preview and
	// the operator may reach it, never the production.
	policy := filepath.Join(appDir, "networkpolicy.yaml")
	if _, err := os.Stat(policy); os.IsNotExist(err) {
		if err := os.WriteFile(policy, []byte(previewDatabaseNetworkPolicy(spec, p)), 0o644); err != nil {
			return false, err
		}
		changed = true
	} else if err != nil {
		return false, err
	}

	// The app kustomization lists the directory of the database.
	kPath := filepath.Join(appDir, "kustomization.yaml")
	raw, err := os.ReadFile(kPath)
	if err != nil {
		return false, err
	}
	if !listedInKustomization(raw, "db") {
		if err := os.WriteFile(kPath, appendKustomizationResource(raw, "db"), 0o644); err != nil {
			return false, err
		}
		changed = true
	}
	return changed, nil
}

// previewDatabaseNetworkPolicy renders the network isolation of the database
// of a preview. The database of a preview is reachable by the app of that
// preview and by the operator, and by nothing else.
func previewDatabaseNetworkPolicy(spec AppSpec, p Platform) string {
	p = p.withDefaults()
	name := PreviewDatabaseName(spec.Name)
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack. Isolated network for the preview database:\n")
	b.WriteString("# only this preview's app and the CNPG operator may reach it.\n")
	b.WriteString("apiVersion: networking.k8s.io/v1\n")
	b.WriteString("kind: NetworkPolicy\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "\n")
	b.WriteString("  namespace: " + p.ReleaseNamespace + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  podSelector:\n")
	b.WriteString("    matchLabels:\n")
	b.WriteString("      cnpg.io/cluster: " + name + "\n")
	b.WriteString("  policyTypes: [Ingress, Egress]\n")
	b.WriteString("  ingress:\n")
	b.WriteString("    - from:\n")
	b.WriteString("        - podSelector:\n")
	b.WriteString("            matchLabels:\n")
	b.WriteString("              app.kubernetes.io/name: " + sanitizeName(spec.Name) + "\n")
	b.WriteString("        - namespaceSelector:\n")
	b.WriteString("            matchLabels:\n")
	b.WriteString("              kubernetes.io/metadata.name: cnpg-system\n")
	b.WriteString("      ports:\n")
	b.WriteString("        - { protocol: TCP, port: 5432 }\n")
	b.WriteString("        - { protocol: TCP, port: 8000 }\n")
	b.WriteString("        - { protocol: TCP, port: 9090 }\n")
	b.WriteString("  egress:\n")
	b.WriteString("    - to:\n")
	b.WriteString("        - namespaceSelector:\n")
	b.WriteString("            matchLabels:\n")
	b.WriteString("              kubernetes.io/metadata.name: kube-system\n")
	b.WriteString("          podSelector:\n")
	b.WriteString("            matchLabels:\n")
	b.WriteString("              k8s-app: kube-dns\n")
	b.WriteString("      ports:\n")
	b.WriteString("        - { protocol: UDP, port: 53 }\n")
	b.WriteString("        - { protocol: TCP, port: 53 }\n")
	b.WriteString("    - to:\n")
	b.WriteString("        - namespaceSelector:\n")
	b.WriteString("            matchLabels:\n")
	b.WriteString("              kubernetes.io/metadata.name: cnpg-system\n")
	b.WriteString("      ports:\n")
	b.WriteString("        - { protocol: TCP, port: 9090 }\n")
	return b.String()
}

// previewDatabaseEnvYAML returns the literal env entries that expose the
// preview database to the app, pulling the value from the CNPG-generated
// Secret (so nothing secret is in Git).
func previewDatabaseEnvYAML(spec AppSpec) string {
	name := PreviewDatabaseName(spec.Name)
	return fmt.Sprintf("- name: DATABASE_URL\n  valueFrom:\n    secretKeyRef:\n      name: %s-app\n      key: uri\n      optional: true\n", name)
}
