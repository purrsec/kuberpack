package promote

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// cnpgEngine renders a PostgreSQL database with CloudNativePG.
//
// CloudNativePG generates the credentials itself: the URI of the database
// lands in the Secret <cluster>-app, under the key `uri`. The engine only
// references it, the value never transits through Kuberpack.
type cnpgEngine struct{}

func (cnpgEngine) Name() string { return "cnpg" }

func (cnpgEngine) Render(dir string, spec AddonSpec, platform Platform) (AddonResult, error) {
	p := platform.withDefaults()
	entry, ok := AddonCatalogEntry("postgres")
	if !ok {
		return AddonResult{}, fmt.Errorf("the type postgres is not in the catalogue")
	}
	plan, err := entry.Plan(spec.Plan, spec.Params)
	if err != nil {
		return AddonResult{}, err
	}
	database := strings.TrimSpace(spec.Database)
	if database == "" {
		database = "app"
	}
	owner := strings.TrimSpace(spec.Owner)
	if owner == "" {
		owner = "app"
	}
	namespace := strings.TrimSpace(spec.Namespace)
	if namespace == "" {
		namespace = p.ReleaseNamespace
	}
	name := sanitizeName(spec.Project) + "-" + sanitizeName(spec.Name)

	// The image of the operator is the platform's choice; the catalogue
	// holds the default. The version the manifest asks for is the one
	// that decides the image: a PostgreSQL 14 and a PostgreSQL 16 do not
	// share their data directory.
	imageRef, _, err := entry.ImageForVersion(spec.Version)
	if err != nil {
		return AddonResult{}, err
	}
	if override := strings.TrimSpace(p.PostgresImage); override != "" {
		imageRef = override
	}
	image, err := p.PinnedImage(imageRef)
	if err != nil {
		return AddonResult{}, err
	}

	var b strings.Builder
	b.WriteString("# Generated by Kuberpack from the project manifest.\n")
	b.WriteString("apiVersion: postgresql.cnpg.io/v1\n")
	b.WriteString("kind: Cluster\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("  labels:\n")
	b.WriteString("    kuberpack.io/addon: " + entry.Kind + "\n")
	b.WriteString("    kuberpack.io/addon-name: " + sanitizeName(spec.Name) + "\n")
	b.WriteString("    kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  instances: " + strconv.Itoa(plan.Instances) + "\n")
	b.WriteString("  imageName: " + image + "\n")
	b.WriteString("  imagePullPolicy: IfNotPresent\n")
	b.WriteString("  inheritedMetadata:\n")
	b.WriteString("    labels:\n")
	b.WriteString("      kuberpack.io/addon: " + entry.Kind + "\n")
	b.WriteString("      kuberpack.io/addon-name: " + sanitizeName(spec.Name) + "\n")
	b.WriteString("      kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	b.WriteString("  primaryUpdateStrategy: unsupervised\n")
	b.WriteString("  enableSuperuserAccess: false\n")
	b.WriteString("  bootstrap:\n")
	b.WriteString("    initdb:\n")
	b.WriteString("      database: " + database + "\n")
	b.WriteString("      owner: " + owner + "\n")
	b.WriteString("      encoding: UTF8\n")
	b.WriteString("      dataChecksums: true\n")
	b.WriteString("  storage:\n")
	b.WriteString("    storageClass: " + p.PostgresStorageClass + "\n")
	b.WriteString("    size: " + plan.Storage + "\n")
	b.WriteString("  resources:\n")
	b.WriteString("    requests: { cpu: " + plan.Resources.Requests.CPU + ", memory: " + plan.Resources.Requests.Memory + " }\n")
	b.WriteString("    limits: { cpu: \"" + plan.Resources.Limits.CPU + "\", memory: \"" + plan.Resources.Limits.Memory + "\" }\n")
	b.WriteString("  monitoring:\n")
	b.WriteString("    enablePodMonitor: false\n")
	// The ObjectStore of the backups, when the project has one.
	var objectStore string
	// The Job that creates the bucket of the backups.
	var bucketJob string
	// The backups go to the object storage of the project. The
	// credentials are references: they never pass through Kuberpack.
	if spec.Backup != nil {
		storage := strings.TrimSpace(spec.Backup.S3)
		if storage != "" {
			kind := spec.Siblings[sanitizeName(storage)]
			if kind != "s3" {
				return AddonResult{}, fmt.Errorf("the addon %q cannot be backed up to %q: it does not speak S3",
					sanitizeName(spec.Name), storage)
			}
			secret := sanitizeName(spec.Project) + "-" + sanitizeName(storage) + "-app"
			endpoint := "http://" + sanitizeName(spec.Project) + "-" + sanitizeName(storage) + "." + namespace + ".svc.cluster.local:9000"
			store := name + "-store"
			// Since CloudNativePG 1.27, the backups go through the
			// barman plugin: the destination is an ObjectStore, and the
			// cluster names the plugin and the store. The operator
			// refuses the in-tree configuration and a plugin at the
			// same time.
			b.WriteString("  plugins:\n")
			b.WriteString("    - name: " + barmanPluginName + "\n")
			b.WriteString("      isWALArchiver: true\n")
			b.WriteString("      parameters:\n")
			b.WriteString("        barmanObjectName: " + store + "\n")
			objectStore = renderObjectStore(store, namespace, sanitizeName(spec.Name), endpoint, secret, spec.Backup.Retention)
			bucketJob = renderBucketJob(name+"-bucket", namespace, sanitizeName(spec.Project), sanitizeName(spec.Name), endpoint, secret)
		} else if retention := strings.TrimSpace(spec.Backup.Retention); retention != "" {
			b.WriteString("  backup:\n")
			b.WriteString("    retentionPolicy: " + retention + "\n")
		}
	}

	if err := writeAddonFiles(dir, addonFile{name: "database.yaml", content: b.String()}); err != nil {
		return AddonResult{}, err
	}
	if objectStore != "" {
		if err := writeAddonFiles(dir, addonFile{name: "objectstore.yaml", content: objectStore}); err != nil {
			return AddonResult{}, err
		}
	}
	if bucketJob != "" {
		if err := writeAddonFiles(dir, addonFile{name: "bucket-job.yaml", content: bucketJob}); err != nil {
			return AddonResult{}, err
		}
	}
	if err := writeAddonFiles(dir, addonFile{name: "dump.yaml", content: databaseDumpJob(name, namespace, database, image)}); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{
		name: "networkpolicy.yaml",
		content: addonNetworkPolicy(name, namespace, entry.Kind, sanitizeName(spec.Name),
			sanitizeName(spec.Project), []int{5432, 8000, 9090}, "cnpg-system"),
	}); err != nil {
		return AddonResult{}, err
	}
	// The scheduled backup: since CNPG 1.27 the operator does not create
	// one any more, and a cluster without one is never backed up.
	var scheduled string
	if spec.Backup != nil && strings.TrimSpace(spec.Backup.S3) != "" {
		scheduled = renderScheduledBackup(name, namespace, spec)
		if err := writeAddonFiles(dir, addonFile{name: "scheduledbackup.yaml", content: scheduled}); err != nil {
			return AddonResult{}, err
		}
	}
	kustomization := addonKustomization("database.yaml", "networkpolicy.yaml")
	if scheduled != "" {
		kustomization = addonKustomization("database.yaml", "networkpolicy.yaml", "scheduledbackup.yaml")
	}
	if objectStore != "" {
		kustomization = addonKustomization("database.yaml", "networkpolicy.yaml", "scheduledbackup.yaml", "objectstore.yaml", "bucket-job.yaml")
	}
	if err := writeAddonFiles(dir, addonFile{
		name:    "kustomization.yaml",
		content: kustomization,
	}); err != nil {
		return AddonResult{}, err
	}

	// The applications that expect the usual variables of a PostgreSQL
	// find them here, with the same secret: no credential is ever written
	// in the repository. The contract is in the catalogue.
	secret := name + "-app"
	envs := make([]AddonEnv, 0, len(entry.Env))
	for _, variable := range sortedKeys(entry.Env) {
		envs = append(envs, AddonEnv{
			Name:       variable,
			SecretName: secret,
			SecretKey:  entry.Env[variable],
		})
	}
	return AddonResult{
		Kind: entry.Kind,
		Port: entry.Port,
		Env:  envs,
	}, nil
}

// sortedKeys lists the keys of a map, in order.
func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for key := range m {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

// databaseDumpJob renders the Job that dumps a database. The data of a
// database leaves the cluster before its project does: the platform refuses
// to remove a project that still holds one, and this Job is how the data is
// taken out.
func databaseDumpJob(name, namespace, database, image string) string {
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack. Dumps the database of the addon.\n")
	b.WriteString("# The dump is in the logs of the Job.\n")
	b.WriteString("apiVersion: batch/v1\n")
	b.WriteString("kind: Job\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "-dump\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  backoffLimit: 1\n")
	b.WriteString("  template:\n")
	b.WriteString("    metadata:\n")
	b.WriteString("      labels:\n")
	b.WriteString("        kuberpack.io/addon: postgres\n")
	b.WriteString("        kuberpack.io/addon-name: " + name + "\n")
	b.WriteString("    spec:\n")
	b.WriteString("      restartPolicy: Never\n")
	b.WriteString("      containers:\n")
	b.WriteString("        - name: dump\n")
	b.WriteString("          image: " + image + "\n")
	b.WriteString("          command: [\"sh\", \"-c\"]\n")
	b.WriteString("          args:\n")
	b.WriteString("            - |\n")
	b.WriteString("              pg_dump --host=\"$PGHOST\" --username=\"$PGUSER\" --dbname=\"$PGDATABASE\"\n")
	b.WriteString("          env:\n")
	b.WriteString("            - name: PGHOST\n")
	b.WriteString("              value: " + name + "-rw\n")
	b.WriteString("            - name: PGDATABASE\n")
	b.WriteString("              value: " + database + "\n")
	b.WriteString("            - name: PGUSER\n")
	b.WriteString("              valueFrom:\n")
	b.WriteString("                secretKeyRef:\n")
	b.WriteString("                  name: " + name + "-app\n")
	b.WriteString("                  key: user\n")
	b.WriteString("            - name: PGPASSWORD\n")
	b.WriteString("              valueFrom:\n")
	b.WriteString("                secretKeyRef:\n")
	b.WriteString("                  name: " + name + "-app\n")
	b.WriteString("                  key: password\n")
	return b.String()
}

// renderScheduledBackup renders the scheduled backup of a cluster.
//
// Since CNPG 1.27 the operator does not create one any more: a cluster
// whose backups live in an object storage needs it, or nothing is ever
// saved. The first backup is immediate: the platform does not wait a day
// to tell whether the backup works.
func renderScheduledBackup(cluster, namespace string, spec AddonSpec) string {
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack from the project manifest.\n")
	b.WriteString("apiVersion: postgresql.cnpg.io/v1\n")
	b.WriteString("kind: ScheduledBackup\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + cluster + "-full\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  schedule: \"0 0 2 * * *\"\n")
	b.WriteString("  method: plugin\n")
	b.WriteString("  pluginConfiguration:\n")
	b.WriteString("    name: " + barmanPluginName + "\n")
	b.WriteString("  immediate: true\n")
	b.WriteString("  backupOwnerReference: self\n")
	b.WriteString("  cluster:\n")
	b.WriteString("    name: " + cluster + "\n")
	return b.String()
}

// barmanPluginName is the name of the plugin barman of CloudNativePG.
// Since 1.27, the backups and the WAL archiving go through it.
const barmanPluginName = "barman-cloud.cloudnative-pg.io"

// renderObjectStore renders the destination of the backups of a database.
//
// The destination is a resource of its own since CloudNativePG 1.27: the
// credentials are references to a secret, they never pass through
// Kuberpack.
func renderObjectStore(name, namespace, database, endpoint, secret, retention string) string {
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack from the project manifest.\n")
	b.WriteString("# The destination of the backups of the database.\n")
	b.WriteString("apiVersion: barmancloud.cnpg.io/v1\n")
	b.WriteString("kind: ObjectStore\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("spec:\n")
	if r := strings.TrimSpace(retention); r != "" {
		b.WriteString("  retentionPolicy: " + r + "\n")
	}
	b.WriteString("  configuration:\n")
	b.WriteString("    destinationPath: s3://" + database + "/\n")
	b.WriteString("    endpointURL: " + endpoint + "\n")
	b.WriteString("    s3Credentials:\n")
	b.WriteString("      accessKeyId:\n")
	b.WriteString("        name: " + secret + "\n")
	b.WriteString("        key: accessKeyId\n")
	b.WriteString("      secretAccessKey:\n")
	b.WriteString("        name: " + secret + "\n")
	b.WriteString("        key: secretAccessKey\n")
	b.WriteString("    wal:\n")
	b.WriteString("      compression: gzip\n")
	b.WriteString("      maxParallel: 2\n")
	return b.String()
}

// renderBucketJob renders the Job that creates the bucket of the backups.
//
// The bucket must exist before the first backup: barman waits for it on
// AWS, and on another object store it simply fails. The Job is
// idempotent, and it waits for the credentials of the storage, which
// another Job creates.
func renderBucketJob(name, namespace, project, bucket, endpoint, secret string) string {
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack from the project manifest.\n")
	b.WriteString("# The bucket of the backups. It must exist before the first backup.\n")
	b.WriteString("apiVersion: batch/v1\n")
	b.WriteString("kind: CronJob\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("  labels:\n")
	b.WriteString("    kuberpack.io/for: " + project + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  # The bucket is created once, but a storage that was wiped\n")
	b.WriteString("  # lost it: the job comes back every day.\n")
	b.WriteString("  schedule: \"17 3 * * *\"\n")
	b.WriteString("  concurrencyPolicy: Forbid\n")
	b.WriteString("  jobTemplate:\n")
	b.WriteString("    spec:\n")
	b.WriteString("      backoffLimit: 6\n")
	b.WriteString("      template:\n")
	b.WriteString("        metadata:\n")
	b.WriteString("          labels:\n")
	b.WriteString("            kuberpack.io/for: " + project + "\n")
	b.WriteString("        spec:\n")
	b.WriteString("          restartPolicy: Never\n")
	b.WriteString("          containers:\n")
	b.WriteString("            - name: bucket\n")
	b.WriteString("              image: " + barmanSidecarImage + "\n")
	b.WriteString("              command: [\"python\", \"-c\"]\n")
	b.WriteString("              args:\n")
	b.WriteString("                - |\n")
	b.WriteString("                  import boto3, os\n")
	b.WriteString("                  client = boto3.client(\n")
	b.WriteString("                      \"s3\",\n")
	b.WriteString("                      endpoint_url=os.environ[\"ENDPOINT\"],\n")
	b.WriteString("                      aws_access_key_id=os.environ[\"ACCESS_KEY_ID\"],\n")
	b.WriteString("                      aws_secret_access_key=os.environ[\"SECRET_ACCESS_KEY\"],\n")
	b.WriteString("                  )\n")
	b.WriteString("                  try:\n")
	b.WriteString("                      client.create_bucket(Bucket=os.environ[\"BUCKET\"])\n")
	b.WriteString("                  except Exception as error:\n")
	b.WriteString("                      # The bucket exists, or the storage refuses\n")
	b.WriteString("                      # to create it. The backup will tell.\n")
	b.WriteString("                      print(error)\n")
	b.WriteString("              env:\n")
	b.WriteString("                - name: ENDPOINT\n")
	b.WriteString("                  value: " + endpoint + "\n")
	b.WriteString("                - name: BUCKET\n")
	b.WriteString("                  value: " + bucket + "\n")
	b.WriteString("                - name: ACCESS_KEY_ID\n")
	b.WriteString("                  valueFrom:\n")
	b.WriteString("                    secretKeyRef:\n")
	b.WriteString("                      name: " + secret + "\n")
	b.WriteString("                      key: accessKeyId\n")
	b.WriteString("                - name: SECRET_ACCESS_KEY\n")
	b.WriteString("                  valueFrom:\n")
	b.WriteString("                    secretKeyRef:\n")
	b.WriteString("                      name: " + secret + "\n")
	b.WriteString("                      key: secretAccessKey\n")
	return b.String()
}

// barmanSidecarImage is the image of the sidecar of the plugin barman.
// It carries boto3, which creates the bucket of the backups.
const barmanSidecarImage = "ghcr.io/cloudnative-pg/plugin-barman-cloud-sidecar@sha256:2287a793a804db751edd0d07d44cd549e357677e98a800eb12e2cf7c0d53f9b0"
