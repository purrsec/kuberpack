package promote

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// cnpgEngine renders a PostgreSQL database with CloudNativePG.
//
// CloudNativePG generates the credentials itself: the URI of the database
// lands in the Secret <cluster>-app, under the key `uri`. The engine only
// references it, the value never transits through Kuberpack.
type cnpgEngine struct{}

func (cnpgEngine) Name() string { return "cnpg" }

func (cnpgEngine) Render(dir string, spec AddonSpec, platform Platform) (AddonResult, error) {
	p := platform.withDefaults()
	entry, ok := AddonCatalogEntry("postgres")
	if !ok {
		return AddonResult{}, fmt.Errorf("the type postgres is not in the catalogue")
	}
	plan, err := entry.Plan(spec.Plan, spec.Params)
	if err != nil {
		return AddonResult{}, err
	}
	database := strings.TrimSpace(spec.Database)
	if database == "" {
		database = "app"
	}
	owner := strings.TrimSpace(spec.Owner)
	if owner == "" {
		owner = "app"
	}
	namespace := strings.TrimSpace(spec.Namespace)
	if namespace == "" {
		namespace = p.ReleaseNamespace
	}
	name := sanitizeName(spec.Project) + "-" + sanitizeName(spec.Name)

	// The image of the operator is the platform's choice; the catalogue
	// holds the default.
	imageRef := strings.TrimSpace(p.PostgresImage)
	if imageRef == "" {
		imageRef = entry.Image
	}
	image, err := p.PinnedImage(imageRef)
	if err != nil {
		return AddonResult{}, err
	}

	var b strings.Builder
	b.WriteString("# Generated by Kuberpack from the project manifest.\n")
	b.WriteString("apiVersion: postgresql.cnpg.io/v1\n")
	b.WriteString("kind: Cluster\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("  labels:\n")
	b.WriteString("    kuberpack.io/addon: " + entry.Kind + "\n")
	b.WriteString("    kuberpack.io/addon-name: " + sanitizeName(spec.Name) + "\n")
	b.WriteString("    kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  instances: " + strconv.Itoa(plan.Instances) + "\n")
	b.WriteString("  imageName: " + image + "\n")
	b.WriteString("  imagePullPolicy: IfNotPresent\n")
	b.WriteString("  inheritedMetadata:\n")
	b.WriteString("    labels:\n")
	b.WriteString("      kuberpack.io/addon: " + entry.Kind + "\n")
	b.WriteString("      kuberpack.io/addon-name: " + sanitizeName(spec.Name) + "\n")
	b.WriteString("      kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	b.WriteString("  primaryUpdateStrategy: unsupervised\n")
	b.WriteString("  enableSuperuserAccess: false\n")
	b.WriteString("  bootstrap:\n")
	b.WriteString("    initdb:\n")
	b.WriteString("      database: " + database + "\n")
	b.WriteString("      owner: " + owner + "\n")
	b.WriteString("      encoding: UTF8\n")
	b.WriteString("      dataChecksums: true\n")
	b.WriteString("  storage:\n")
	b.WriteString("    storageClass: " + p.PostgresStorageClass + "\n")
	b.WriteString("    size: " + plan.Storage + "\n")
	b.WriteString("  resources:\n")
	b.WriteString("    requests: { cpu: " + plan.Resources.Requests.CPU + ", memory: " + plan.Resources.Requests.Memory + " }\n")
	b.WriteString("    limits: { cpu: \"" + plan.Resources.Limits.CPU + "\", memory: \"" + plan.Resources.Limits.Memory + "\" }\n")
	b.WriteString("  monitoring:\n")
	b.WriteString("    enablePodMonitor: false\n")
	// The backups go to the object storage of the project. The
	// credentials are references: they never pass through Kuberpack.
	if spec.Backup != nil {
		storage := strings.TrimSpace(spec.Backup.S3)
		if storage != "" {
			kind := spec.Siblings[sanitizeName(storage)]
			if kind != "s3" {
				return AddonResult{}, fmt.Errorf("the addon %q cannot be backed up to %q: it does not speak S3",
					sanitizeName(spec.Name), storage)
			}
			secret := sanitizeName(spec.Project) + "-" + sanitizeName(storage) + "-app"
			endpoint := "http://" + sanitizeName(spec.Project) + "-" + sanitizeName(storage) + "." + namespace + ".svc.cluster.local:9000"
			b.WriteString("  backup:\n")
			b.WriteString("    barmanObjectStore:\n")
			b.WriteString("      destinationPath: s3://" + sanitizeName(spec.Name) + "/\n")
			b.WriteString("      endpointURL: " + endpoint + "\n")
			b.WriteString("      s3Credentials:\n")
			b.WriteString("        accessKeyId:\n")
			b.WriteString("          name: " + secret + "\n")
			b.WriteString("          key: accessKeyId\n")
			b.WriteString("        secretAccessKey:\n")
			b.WriteString("          name: " + secret + "\n")
			b.WriteString("          key: secretAccessKey\n")
			b.WriteString("      wal:\n")
			b.WriteString("        compression: gzip\n")
			b.WriteString("        maxParallel: 2\n")
			if retention := strings.TrimSpace(spec.Backup.Retention); retention != "" {
				b.WriteString("      retentionPolicy: " + retention + "\n")
			}
		} else if retention := strings.TrimSpace(spec.Backup.Retention); retention != "" {
			b.WriteString("  backup:\n")
			b.WriteString("    retentionPolicy: " + retention + "\n")
		}
	}

	if err := writeAddonFiles(dir, addonFile{name: "database.yaml", content: b.String()}); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{name: "dump.yaml", content: databaseDumpJob(name, namespace, database, image)}); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{
		name: "networkpolicy.yaml",
		content: addonNetworkPolicy(name, namespace, entry.Kind, sanitizeName(spec.Name),
			sanitizeName(spec.Project), []int{5432, 8000, 9090}, "cnpg-system"),
	}); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{
		name:    "kustomization.yaml",
		content: addonKustomization("database.yaml", "networkpolicy.yaml"),
	}); err != nil {
		return AddonResult{}, err
	}

	// The applications that expect the usual variables of a PostgreSQL
	// find them here, with the same secret: no credential is ever written
	// in the repository. The contract is in the catalogue.
	secret := name + "-app"
	envs := make([]AddonEnv, 0, len(entry.Env))
	for _, variable := range sortedKeys(entry.Env) {
		envs = append(envs, AddonEnv{
			Name:       variable,
			SecretName: secret,
			SecretKey:  entry.Env[variable],
		})
	}
	return AddonResult{
		Kind: entry.Kind,
		Port: entry.Port,
		Env:  envs,
	}, nil
}

// sortedKeys lists the keys of a map, in order.
func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for key := range m {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

// databaseDumpJob renders the Job that dumps a database. The data of a
// database leaves the cluster before its project does: the platform refuses
// to remove a project that still holds one, and this Job is how the data is
// taken out.
func databaseDumpJob(name, namespace, database, image string) string {
	var b strings.Builder
	b.WriteString("# Generated by Kuberpack. Dumps the database of the addon.\n")
	b.WriteString("# The dump is in the logs of the Job.\n")
	b.WriteString("apiVersion: batch/v1\n")
	b.WriteString("kind: Job\n")
	b.WriteString("metadata:\n")
	b.WriteString("  name: " + name + "-dump\n")
	b.WriteString("  namespace: " + namespace + "\n")
	b.WriteString("spec:\n")
	b.WriteString("  backoffLimit: 1\n")
	b.WriteString("  template:\n")
	b.WriteString("    metadata:\n")
	b.WriteString("      labels:\n")
	b.WriteString("        kuberpack.io/addon: postgres\n")
	b.WriteString("        kuberpack.io/addon-name: " + name + "\n")
	b.WriteString("    spec:\n")
	b.WriteString("      restartPolicy: Never\n")
	b.WriteString("      containers:\n")
	b.WriteString("        - name: dump\n")
	b.WriteString("          image: " + image + "\n")
	b.WriteString("          command: [\"sh\", \"-c\"]\n")
	b.WriteString("          args:\n")
	b.WriteString("            - |\n")
	b.WriteString("              pg_dump --host=\"$PGHOST\" --username=\"$PGUSER\" --dbname=\"$PGDATABASE\"\n")
	b.WriteString("          env:\n")
	b.WriteString("            - name: PGHOST\n")
	b.WriteString("              value: " + name + "-rw\n")
	b.WriteString("            - name: PGDATABASE\n")
	b.WriteString("              value: " + database + "\n")
	b.WriteString("            - name: PGUSER\n")
	b.WriteString("              valueFrom:\n")
	b.WriteString("                secretKeyRef:\n")
	b.WriteString("                  name: " + name + "-app\n")
	b.WriteString("                  key: user\n")
	b.WriteString("            - name: PGPASSWORD\n")
	b.WriteString("              valueFrom:\n")
	b.WriteString("                secretKeyRef:\n")
	b.WriteString("                  name: " + name + "-app\n")
	b.WriteString("                  key: password\n")
	return b.String()
}
