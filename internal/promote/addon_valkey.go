package promote

import (
	"strings"
)

// valkeyEngine renders a Valkey cache (Redis compatible).
//
// The cache is private to the cluster: it has no password, and the
// NetworkPolicy of the project is what isolates it. A service that declares
// the addon in the manifest gets its URL.
type valkeyEngine struct{}

func (valkeyEngine) Name() string { return "valkey" }

func (valkeyEngine) Render(dir string, spec AddonSpec, platform Platform) (AddonResult, error) {
	p := platform.withDefaults()
	namespace := strings.TrimSpace(spec.Namespace)
	if namespace == "" {
		namespace = p.ReleaseNamespace
	}
	name := sanitizeName(spec.Project) + "-" + sanitizeName(spec.Name)
	labels := "    kuberpack.io/addon: valkey\n    kuberpack.io/for: " + sanitizeName(spec.Project) + "\n"

	var stateful strings.Builder
	stateful.WriteString("# Generated by Kuberpack from the project manifest.\n")
	stateful.WriteString("apiVersion: apps/v1\n")
	stateful.WriteString("kind: StatefulSet\n")
	stateful.WriteString("metadata:\n")
	stateful.WriteString("  name: " + name + "\n")
	stateful.WriteString("  namespace: " + namespace + "\n")
	stateful.WriteString("  labels:\n")
	stateful.WriteString(labels)
	stateful.WriteString("spec:\n")
	stateful.WriteString("  serviceName: " + name + "\n")
	stateful.WriteString("  replicas: 1\n")
	stateful.WriteString("  selector:\n")
	stateful.WriteString("    matchLabels:\n")
	stateful.WriteString("      app.kubernetes.io/name: " + name + "\n")
	stateful.WriteString("      app.kubernetes.io/part-of: kuberpack\n")
	stateful.WriteString("  template:\n")
	stateful.WriteString("    metadata:\n")
	stateful.WriteString("      labels:\n")
	stateful.WriteString("        app.kubernetes.io/name: " + name + "\n")
	stateful.WriteString("        app.kubernetes.io/part-of: kuberpack\n")
	stateful.WriteString("        kuberpack.io/addon: valkey\n")
	stateful.WriteString("        kuberpack.io/for: " + sanitizeName(spec.Project) + "\n")
	stateful.WriteString("    spec:\n")
	stateful.WriteString("      containers:\n")
	stateful.WriteString("        - name: valkey\n")
	stateful.WriteString("          image: " + p.AddonImages["valkey"] + "\n")
	stateful.WriteString("          imagePullPolicy: IfNotPresent\n")
	stateful.WriteString("          args: [\"--save\", \"\", \"--appendonly\", \"no\"]\n")
	stateful.WriteString("          ports:\n")
	stateful.WriteString("            - name: valkey\n")
	stateful.WriteString("              containerPort: 6379\n")
	stateful.WriteString("          resources:\n")
	stateful.WriteString("            requests: { cpu: 50m, memory: 128Mi }\n")
	stateful.WriteString("            limits: { cpu: \"1\", memory: 512Mi }\n")
	stateful.WriteString("          volumeMounts:\n")
	stateful.WriteString("            - name: data\n")
	stateful.WriteString("              mountPath: /data\n")
	stateful.WriteString("  volumeClaimTemplates:\n")
	stateful.WriteString("    - metadata:\n")
	stateful.WriteString("        name: data\n")
	stateful.WriteString("      spec:\n")
	stateful.WriteString("        accessModes: [\"ReadWriteOnce\"]\n")
	stateful.WriteString("        resources:\n")
	stateful.WriteString("          requests:\n")
	stateful.WriteString("            storage: " + p.AddonStorage["valkey"] + "\n")
	if p.AddonStorageClass != "" {
		stateful.WriteString("        storageClassName: " + p.AddonStorageClass + "\n")
	}

	var service strings.Builder
	service.WriteString("# Generated by Kuberpack from the project manifest.\n")
	service.WriteString("apiVersion: v1\n")
	service.WriteString("kind: Service\n")
	service.WriteString("metadata:\n")
	service.WriteString("  name: " + name + "\n")
	service.WriteString("  namespace: " + namespace + "\n")
	service.WriteString("  labels:\n")
	service.WriteString(labels)
	service.WriteString("spec:\n")
	service.WriteString("  selector:\n")
	service.WriteString("    app.kubernetes.io/name: " + name + "\n")
	service.WriteString("    app.kubernetes.io/part-of: kuberpack\n")
	service.WriteString("  ports:\n")
	service.WriteString("    - name: valkey\n")
	service.WriteString("      port: 6379\n")
	service.WriteString("      targetPort: valkey\n")

	if err := writeAddonFiles(dir,
		addonFile{name: "valkey.yaml", content: stateful.String()},
		addonFile{name: "service.yaml", content: service.String()},
	); err != nil {
		return AddonResult{}, err
	}
	if err := writeAddonFiles(dir, addonFile{
		name:    "kustomization.yaml",
		content: addonKustomization("valkey.yaml", "service.yaml"),
	}); err != nil {
		return AddonResult{}, err
	}

	return AddonResult{
		Kind: "valkey",
		Port: 6379,
		Env: []AddonEnv{{
			Name:  "VALKEY_URL",
			Value: "valkey://" + name + ":6379",
		}},
	}, nil
}
